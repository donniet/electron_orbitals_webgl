#!/usr/bin/env python3
"""Generate the orbital column-density lookup tables (stdlib only).

Two outputs:

* General moment tables (periods 1-4): data/orbital_tables.bin (float32 LE)
  + data/orbital_tables.json (metadata). See tools/orbitals.py for the math:
  for each radial function (1s 2s 3s 4s 2p 3p 4p 3d) the moments
  I_k(u) = int R^2 t^k / r^(2l) dt, k = 0, 2, 4, in the scaled variable
  u = Z b / n, stored as texture rows (I0, I2, I4, 0).

* LEGACY (H-Ne only, used by the app until the Phase B refactor):
  js/orbital_tables.js, described below.

--- legacy tables ---

All quantities are in *scaled* atomic units for a hydrogen-like orbital with
Z = 1 (lengths in Bohr radii). For an orbital with effective charge Z the
density is rho_Z(r) = Z^3 rho_1(Z r), so a column density through the real
atom is  col_Z = Z^2 * col_1(Z * p, d).

Densities (Z = 1):
    1s : |psi|^2 = exp(-2r) / pi
    2s : |psi|^2 = (2 - r)^2 exp(-r) / (32 pi)
    2pz: |psi|^2 = z^2 exp(-r) / (32 pi)        (likewise x^2, y^2 for 2px, 2py)

A ray is r(t) = p + t d with |d| = 1 and p the point of closest approach to
the nucleus (p . d = 0, b = |p|). Integrating along the ray:

    col_1s(b)  = S_1s(b)          = int exp(-2 sqrt(b^2+t^2)) / pi dt
    col_2s(b)  = S_2s(b)          = int (2-r)^2 exp(-r) / (32 pi) dt
    col_2pz    = p_z^2 A(b) + d_z^2 B(b)
        A(b) = int exp(-r) / (32 pi) dt
        B(b) = int t^2 exp(-r) / (32 pi) dt
(the cross term 2 p_z d_z t is odd in t and integrates to zero).

The four tables are written interleaved as RGBA = (A, B, S_1s, S_2s), sampled
at b_i = i * B_MAX / (N - 1), to js/orbital_tables.js.

`--verify` additionally runs a Monte Carlo simulation: electron positions are
sampled from |psi|^2, projected onto an image plane and histogrammed; the
histograms are compared to the tables.
"""
import argparse
import array
import json
import math
import multiprocessing
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import orbitals as orb  # noqa: E402

N = 1024
B_MAX = 30.0
T_MAX = 70.0          # exp(-70) ~ 4e-31: the integrand is negligible beyond
T_STEPS = 6000        # Simpson intervals on [0, T_MAX] (even)

CHANNELS = ("A_2p", "B_2p", "S_1s", "S_2s")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_PATH = os.path.join(ROOT, "js", "orbital_tables.js")


# ---------------------------------------------------------------- densities
def rho_1s(x, y, z):
    r = math.sqrt(x * x + y * y + z * z)
    return math.exp(-2.0 * r) / math.pi


def rho_2s(x, y, z):
    r = math.sqrt(x * x + y * y + z * z)
    return (2.0 - r) ** 2 * math.exp(-r) / (32.0 * math.pi)


def rho_2p(axis):
    def f(x, y, z):
        r = math.sqrt(x * x + y * y + z * z)
        c = (x, y, z)[axis]
        return c * c * math.exp(-r) / (32.0 * math.pi)
    return f


# ---------------------------------------------------------------- tables
def tables_at(b):
    """Return (A, B, S_1s, S_2s) at impact parameter b (scaled units)."""
    h = T_MAX / T_STEPS
    a = bb = s1 = s2 = 0.0
    for i in range(T_STEPS + 1):
        t = i * h
        w = 1.0 if i in (0, T_STEPS) else (4.0 if i & 1 else 2.0)
        r = math.sqrt(b * b + t * t)
        e = math.exp(-r)
        a += w * e
        bb += w * t * t * e
        s1 += w * e * e
        s2 += w * (2.0 - r) ** 2 * e
    f = 2.0 * h / 3.0          # Simpson weight x2 for the symmetric half-line
    k = 1.0 / (32.0 * math.pi)
    return (a * f * k, bb * f * k, s1 * f / math.pi, s2 * f * k)


def build_tables(n=N, b_max=B_MAX):
    return [tables_at(i * b_max / (n - 1)) for i in range(n)]


def write_js(rows, path=OUT_PATH, b_max=B_MAX):
    n = len(rows)
    flat = [v for row in rows for v in row]
    lines = []
    for i in range(0, len(flat), 8):
        lines.append("  " + ", ".join("%.7g" % v for v in flat[i:i + 8]) + ",")
    src = (
        "// Generated by tools/gen_tables.py -- do not edit by hand.\n"
        "// Column-density tables for hydrogen-like orbitals in scaled units\n"
        "// (Z = 1). RGBA texel i holds (A_2p, B_2p, S_1s, S_2s) at\n"
        "// b = i * TABLE_B_MAX / (TABLE_N - 1).\n"
        f"export const TABLE_N = {n};\n"
        f"export const TABLE_B_MAX = {b_max!r};\n"
        f"export const TABLE_CHANNELS = {list(CHANNELS)!r};\n"
        "export const TABLE_DATA = new Float32Array([\n"
        + "\n".join(lines)
        + "\n]);\n"
    )
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(src)


# ---------------------------------------------------------------- lookup
def lookup(rows, ch, b, b_max=B_MAX):
    """Linear interpolation, identical to the shader / js/math.js."""
    n = len(rows)
    x = b / b_max * (n - 1)
    if x >= n - 1:
        return 0.0
    i = int(x)
    f = x - i
    return rows[i][ch] * (1.0 - f) + rows[i + 1][ch] * f


# ---------------------------------------------------------------- Monte Carlo
def sample_1s(rng):
    # radial pdf r^2 exp(-2r): Gamma(3, 1/2)
    r = -0.5 * math.log(rng.random() * rng.random() * rng.random() or 1e-300)
    return _iso(rng, r)


def sample_2s(rng):
    # Radial pdf ~ r^2 (2-r)^2 exp(-r). Rejection sampling from the mixture
    # proposal q(r) = 0.5 Gamma(3,1) + 0.5 Gamma(5,1)
    #              ~ (r^2/4 + r^4/48) exp(-r).
    # p/q = (2-r)^2 / (1/4 + r^2/48) is bounded by 48 (its limit as r -> inf).
    while True:
        r = _gamma_int(rng, 3) if rng.random() < 0.5 else _gamma_int(rng, 5)
        q = 0.25 * r * r + r ** 4 / 48.0
        p = r * r * (2.0 - r) ** 2
        if rng.random() * 48.0 * q <= p:
            return _iso(rng, r)


def sample_2p(rng, axis):
    # radial pdf r^4 exp(-r): Gamma(5,1); angular pdf ~ cos^2(theta)
    r = _gamma_int(rng, 5)
    u = rng.random()
    c = u ** (1.0 / 3.0) * (1.0 if rng.random() < 0.5 else -1.0)
    s = math.sqrt(max(0.0, 1.0 - c * c))
    phi = 2.0 * math.pi * rng.random()
    v = [s * math.cos(phi) * r, s * math.sin(phi) * r, c * r]
    # v currently has its lobe along z; rotate so the lobe is along `axis`
    if axis == 0:
        v = [v[2], v[0], v[1]]
    elif axis == 1:
        v = [v[1], v[2], v[0]]
    return v


def _gamma_int(rng, k):
    p = 1.0
    for _ in range(k):
        p *= rng.random()
    return -math.log(p or 1e-300)


def _iso(rng, r):
    c = 2.0 * rng.random() - 1.0
    s = math.sqrt(1.0 - c * c)
    phi = 2.0 * math.pi * rng.random()
    return [r * s * math.cos(phi), r * s * math.sin(phi), r * c]


def mc_radial_histogram(samples, proj_axis, weight_axis=None, bin_w=0.5, nbins=16):
    """Histogram of impact parameter b when projecting along `proj_axis`.

    If weight_axis is given, also returns the per-bin sum of the squared
    coordinate along weight_axis (used to test the p_z^2 A(b) term).
    Returns per-bin fraction of samples (and optional weights).
    """
    counts = [0] * nbins
    for v in samples:
        q = [v[i] for i in range(3) if i != proj_axis]
        b = math.hypot(q[0], q[1])
        k = int(b / bin_w)
        if k < nbins:
            counts[k] += 1
    n = len(samples)
    return [c / n for c in counts]


def table_ring_mass(rows, kind, bin_w=0.5, nbins=16, sub=50):
    """Integral of the column density over annuli [k w, (k+1) w).

    kind: 's1', 's2'                  -> 2 pi b S(b)
          'p_along'  (ray || lobe)    -> 2 pi b B(b)
          'p_across' (ray _|_ lobe)   -> pi b^3 A(b)   (p_z^2 averaged = b^2/2)
    """
    out = []
    for k in range(nbins):
        acc = 0.0
        h = bin_w / sub
        for j in range(sub):
            b = (k * bin_w) + (j + 0.5) * h
            if kind == "s1":
                acc += 2 * math.pi * b * lookup(rows, 2, b)
            elif kind == "s2":
                acc += 2 * math.pi * b * lookup(rows, 3, b)
            elif kind == "p_along":
                acc += 2 * math.pi * b * lookup(rows, 1, b)
            elif kind == "p_across":
                acc += math.pi * b ** 3 * lookup(rows, 0, b)
        out.append(acc * h)
    return out


def monte_carlo_verify(rows, n_samples=200000, seed=1, verbose=True):
    """Compare MC histograms with the tables. Returns max abs error."""
    rng = random.Random(seed)
    cases = [
        ("1s", [sample_1s(rng) for _ in range(n_samples)], 2, "s1"),
        ("2s", [sample_2s(rng) for _ in range(n_samples)], 2, "s2"),
        ("2pz along z", [sample_2p(rng, 2) for _ in range(n_samples)], 2, "p_along"),
        ("2pz along x", [sample_2p(rng, 2) for _ in range(n_samples)], 0, "p_across"),
    ]
    worst = 0.0
    for name, samples, axis, kind in cases:
        mc = mc_radial_histogram(samples, axis)
        tb = table_ring_mass(rows, kind)
        err = max(abs(a - b) for a, b in zip(mc, tb))
        worst = max(worst, err)
        if verbose:
            print(f"  MC {name:12s} max |hist - table| = {err:.4f}"
                  f"  (table mass in bins: {sum(tb):.4f})")
    return worst


# ================================================================ moment tables
M_N = 1024            # samples per row
M_U_MAX = 30.0        # scaled impact parameter range u = Z b / n
M_T_MAX = 40.0        # integrate t in [0, M_T_MAX] (exp(-80) beyond)
M_T_STEPS = 4000      # Simpson intervals (even)
BIN_PATH = os.path.join(ROOT, "data", "orbital_tables.bin")
META_PATH = os.path.join(ROOT, "data", "orbital_tables.json")


def moments_at(u):
    """[[I0, I2, I4] per radial row] at scaled impact parameter u."""
    h = M_T_MAX / M_T_STEPS
    rads = orb.RADIALS
    acc = [[0.0, 0.0, 0.0] for _ in rads]
    polys = [(r.norm, r.poly) for r in rads]
    for i in range(M_T_STEPS + 1):
        t = i * h
        w = 1.0 if i in (0, M_T_STEPS) else (4.0 if i & 1 else 2.0)
        r = math.sqrt(u * u + t * t)
        we = w * math.exp(-2.0 * r)
        t2 = t * t
        for row, (norm, poly) in enumerate(polys):
            v = 0.0
            for c in reversed(poly):
                v = v * r + c
            q2 = we * norm * norm * v * v
            a = acc[row]
            a[0] += q2
            a[1] += q2 * t2
            a[2] += q2 * t2 * t2
    f = 2.0 * h / 3.0     # Simpson weight x2 for the symmetric half-line
    return [[v * f for v in a] for a in acc]


def build_moment_tables(n=M_N, u_max=M_U_MAX, processes=None):
    """tables[row][i] = (I0, I2, I4) at u_i = i * u_max / (n - 1)."""
    us = [i * u_max / (n - 1) for i in range(n)]
    with multiprocessing.Pool(processes) as pool:
        per_u = pool.map(moments_at, us, chunksize=16)
    return [[per_u[i][row] for i in range(n)] for row in range(len(orb.RADIALS))]


def write_moment_tables(tables, bin_path=BIN_PATH, meta_path=META_PATH):
    n = len(tables[0])
    arr = array.array("f")
    for row in tables:
        for i0, i2, i4 in row:
            arr.extend((i0, i2, i4, 0.0))
    if sys.byteorder == "big":
        arr.byteswap()
    os.makedirs(os.path.dirname(bin_path), exist_ok=True)
    with open(bin_path, "wb") as fh:
        arr.tofile(fh)
    meta = {
        "generator": "tools/gen_tables.py",
        "format": "float32 little-endian, layout [row][i][channel], RGBA texel per sample",
        "N": n,
        "uMax": M_U_MAX,
        "channels": ["I0", "I2", "I4", "unused"],
        "rows": [{"name": nm, "n": nn, "l": ll}
                 for nm, (nn, ll) in zip(orb.ROW_NAMES, orb.RADIAL)],
    }
    with open(meta_path, "w") as fh:
        json.dump(meta, fh, indent=2)
        fh.write("\n")


def load_moment_tables(bin_path=BIN_PATH, meta_path=META_PATH):
    with open(meta_path) as fh:
        meta = json.load(fh)
    arr = array.array("f")
    with open(bin_path, "rb") as fh:
        arr.frombytes(fh.read())
    if sys.byteorder == "big":
        arr.byteswap()
    n, rows = meta["N"], len(meta["rows"])
    assert len(arr) == rows * n * 4, (len(arr), rows, n)
    tables = [[(arr[(r * n + i) * 4], arr[(r * n + i) * 4 + 1], arr[(r * n + i) * 4 + 2])
               for i in range(n)] for r in range(rows)]
    return tables, meta


def moment_lookup(tables, row, k, u, u_max=M_U_MAX):
    """Linear interpolation of I_k for `row` at u (0 beyond the table)."""
    t = tables[row]
    n = len(t)
    x = u / u_max * (n - 1)
    if x >= n - 1:
        return 0.0
    i = int(x)
    f = x - i
    ch = k // 2
    return t[i][ch] * (1.0 - f) + t[i + 1][ch] * f


def moments_fn(tables, row):
    return lambda k, b: moment_lookup(tables, row, k, b)


# ---------------------------------------------------------------- general Monte Carlo
class RadialSampler:
    """Inverse-CDF sampler for the radial pdf u^2 R_ref(u)^2 (reference units)."""

    def __init__(self, radial, u_max=40.0, n=20000):
        self.us = [u_max * i / n for i in range(n + 1)]
        cdf = [0.0]
        prev = 0.0
        for i in range(1, n + 1):
            u = self.us[i]
            cur = u * u * radial.R(u) ** 2
            cdf.append(cdf[-1] + 0.5 * (prev + cur) * (u_max / n))
            prev = cur
        self.cdf = [c / cdf[-1] for c in cdf]

    def sample(self, rng):
        y = rng.random()
        lo, hi = 0, len(self.cdf) - 1
        while hi - lo > 1:
            mid = (lo + hi) // 2
            if self.cdf[mid] < y:
                lo = mid
            else:
                hi = mid
        c0, c1 = self.cdf[lo], self.cdf[hi]
        f = 0.0 if c1 == c0 else (y - c0) / (c1 - c0)
        return self.us[lo] + f * (self.us[hi] - self.us[lo])


def sample_shape(shape, rng, radial_sampler, amax):
    """Electron position in reference units from |psi|^2 of `shape`."""
    r = radial_sampler.sample(rng)
    while True:
        v = _iso(rng, 1.0)
        if rng.random() * amax <= shape.angular2(v):
            return [c * r for c in v]


def _basis(d):
    a = [1.0, 0.0, 0.0] if abs(d[0]) < 0.9 else [0.0, 1.0, 0.0]
    e1 = [a[1] * d[2] - a[2] * d[1], a[2] * d[0] - a[0] * d[2], a[0] * d[1] - a[1] * d[0]]
    n1 = math.sqrt(orb.dot(e1, e1))
    e1 = [c / n1 for c in e1]
    e2 = [d[1] * e1[2] - d[2] * e1[1], d[2] * e1[0] - d[0] * e1[2], d[0] * e1[1] - d[1] * e1[0]]
    return e1, e2


def ring_masses_from_tables(tables, shape, d, bin_w, nbins, sub=20, nphi=48):
    e1, e2 = _basis(d)
    mom = moments_fn(tables, shape.row)
    out = []
    h = bin_w / sub
    for k in range(nbins):
        acc = 0.0
        for j in range(sub):
            b = k * bin_w + (j + 0.5) * h
            ring = 0.0
            for m in range(nphi):
                ph = 2 * math.pi * (m + 0.5) / nphi
                p = [b * (math.cos(ph) * e1[i] + math.sin(ph) * e2[i]) for i in range(3)]
                ring += shape.column_ref(mom, p, d)
            acc += ring * (2 * math.pi / nphi) * b
        out.append(acc * h)
    return out


def mc_shape_check(tables, shape, d, n_samples=40000, seed=1, bin_w=None, nbins=16):
    """Max |MC histogram - table| of projected impact parameter (ref units)."""
    rng = random.Random(seed)
    sampler = RadialSampler(shape.radial)
    amax = shape.angular2_max()
    rms = math.sqrt(orb.mean_r2(shape.n, shape.l, shape.n))
    bin_w = bin_w or rms / 6
    counts = [0] * nbins
    for _ in range(n_samples):
        x = sample_shape(shape, rng, sampler, amax)
        t = orb.dot(x, d)
        b = math.sqrt(max(0.0, orb.dot(x, x) - t * t))
        kk = int(b / bin_w)
        if kk < nbins:
            counts[kk] += 1
    mc = [c / n_samples for c in counts]
    tb = ring_masses_from_tables(tables, shape, d, bin_w, nbins)
    return max(abs(a - b) for a, b in zip(mc, tb)), sum(tb)


MC_CASES = [  # (shape label, view direction)
    ("1s", [0, 0, 1]), ("3s", [0, 0, 1]), ("4s", [0.6, 0, 0.8]),
    ("3pz", [0, 0, 1]), ("4px", [0, 0.6, 0.8]), ("2py", [1, 0, 0]),
    ("3dxy", [0, 0, 1]), ("3dz2", [0.6, 0, 0.8]), ("3dx2-y2", [0.36, 0.48, 0.8]),
]


def monte_carlo_verify_moments(tables, n_samples=60000, verbose=True):
    shapes = {s.label: s for s in orb.all_shapes()}
    worst = 0.0
    for i, (lab, d) in enumerate(MC_CASES):
        err, mass = mc_shape_check(tables, shapes[lab], d, n_samples, seed=10 + i)
        worst = max(worst, err)
        if verbose:
            print(f"  MC {lab:8s} d={d}  max |hist - table| = {err:.4f}  (mass in bins {mass:.3f})")
    return worst


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--verify", action="store_true",
                    help="run Monte Carlo cross-check after generating")
    ap.add_argument("--out", default=OUT_PATH)
    args = ap.parse_args(argv)

    print(f"Building moment tables: {len(orb.RADIALS)} radial functions x {M_N} samples, "
          f"u in [0, {M_U_MAX}] ...")
    tables = build_moment_tables()
    write_moment_tables(tables)
    print(f"Wrote {BIN_PATH} and {META_PATH}")
    for name, (n, l), row in zip(orb.ROW_NAMES, orb.RADIAL, tables):
        print(f"  {name}: I0(0)={row[0][0]:.6g}  I2(0)={row[0][1]:.6g}  I4(0)={row[0][2]:.6g}")

    print(f"Building LEGACY tables ({len(CHANNELS)} x {N}, b in [0, {B_MAX}]) ...")
    rows = build_tables()
    write_js(rows, args.out)
    print(f"Wrote {args.out}")

    # quick normalisation report
    h = B_MAX / (N - 1)
    norm = [0.0] * 4
    for i, row in enumerate(rows):
        b = i * h
        w = 0.5 if i in (0, N - 1) else 1.0
        norm[0] += w * math.pi * b ** 3 * row[0]
        norm[1] += w * 2 * math.pi * b * row[1]
        norm[2] += w * 2 * math.pi * b * row[2]
        norm[3] += w * 2 * math.pi * b * row[3]
    print("Normalisation (should all be 1):",
          ", ".join(f"{c}={v * h:.5f}" for c, v in zip(CHANNELS, norm)))

    if args.verify:
        print("Monte Carlo verification (legacy) ...")
        worst = monte_carlo_verify(rows)
        print("Monte Carlo verification (moment tables) ...")
        worst = max(worst, monte_carlo_verify_moments(tables))
        ok = worst < 0.01
        print("PASS" if ok else "FAIL", f"(worst bin error {worst:.4f})")
        return 0 if ok else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
