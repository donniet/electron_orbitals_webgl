#!/usr/bin/env python3
"""Generate the orbital column-density lookup tables (stdlib only).

All quantities are in *scaled* atomic units for a hydrogen-like orbital with
Z = 1 (lengths in Bohr radii). For an orbital with effective charge Z the
density is rho_Z(r) = Z^3 rho_1(Z r), so a column density through the real
atom is  col_Z = Z^2 * col_1(Z * p, d).

Densities (Z = 1):
    1s : |psi|^2 = exp(-2r) / pi
    2s : |psi|^2 = (2 - r)^2 exp(-r) / (32 pi)
    2pz: |psi|^2 = z^2 exp(-r) / (32 pi)        (likewise x^2, y^2 for 2px, 2py)

A ray is r(t) = p + t d with |d| = 1 and p the point of closest approach to
the nucleus (p . d = 0, b = |p|). Integrating along the ray:

    col_1s(b)  = S_1s(b)          = int exp(-2 sqrt(b^2+t^2)) / pi dt
    col_2s(b)  = S_2s(b)          = int (2-r)^2 exp(-r) / (32 pi) dt
    col_2pz    = p_z^2 A(b) + d_z^2 B(b)
        A(b) = int exp(-r) / (32 pi) dt
        B(b) = int t^2 exp(-r) / (32 pi) dt
(the cross term 2 p_z d_z t is odd in t and integrates to zero).

The four tables are written interleaved as RGBA = (A, B, S_1s, S_2s), sampled
at b_i = i * B_MAX / (N - 1), to js/orbital_tables.js.

`--verify` additionally runs a Monte Carlo simulation: electron positions are
sampled from |psi|^2, projected onto an image plane and histogrammed; the
histograms are compared to the tables.
"""
import argparse
import math
import os
import random
import sys

N = 1024
B_MAX = 30.0
T_MAX = 70.0          # exp(-70) ~ 4e-31: the integrand is negligible beyond
T_STEPS = 6000        # Simpson intervals on [0, T_MAX] (even)

CHANNELS = ("A_2p", "B_2p", "S_1s", "S_2s")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_PATH = os.path.join(ROOT, "js", "orbital_tables.js")


# ---------------------------------------------------------------- densities
def rho_1s(x, y, z):
    r = math.sqrt(x * x + y * y + z * z)
    return math.exp(-2.0 * r) / math.pi


def rho_2s(x, y, z):
    r = math.sqrt(x * x + y * y + z * z)
    return (2.0 - r) ** 2 * math.exp(-r) / (32.0 * math.pi)


def rho_2p(axis):
    def f(x, y, z):
        r = math.sqrt(x * x + y * y + z * z)
        c = (x, y, z)[axis]
        return c * c * math.exp(-r) / (32.0 * math.pi)
    return f


# ---------------------------------------------------------------- tables
def tables_at(b):
    """Return (A, B, S_1s, S_2s) at impact parameter b (scaled units)."""
    h = T_MAX / T_STEPS
    a = bb = s1 = s2 = 0.0
    for i in range(T_STEPS + 1):
        t = i * h
        w = 1.0 if i in (0, T_STEPS) else (4.0 if i & 1 else 2.0)
        r = math.sqrt(b * b + t * t)
        e = math.exp(-r)
        a += w * e
        bb += w * t * t * e
        s1 += w * e * e
        s2 += w * (2.0 - r) ** 2 * e
    f = 2.0 * h / 3.0          # Simpson weight x2 for the symmetric half-line
    k = 1.0 / (32.0 * math.pi)
    return (a * f * k, bb * f * k, s1 * f / math.pi, s2 * f * k)


def build_tables(n=N, b_max=B_MAX):
    return [tables_at(i * b_max / (n - 1)) for i in range(n)]


def write_js(rows, path=OUT_PATH, b_max=B_MAX):
    n = len(rows)
    flat = [v for row in rows for v in row]
    lines = []
    for i in range(0, len(flat), 8):
        lines.append("  " + ", ".join("%.7g" % v for v in flat[i:i + 8]) + ",")
    src = (
        "// Generated by tools/gen_tables.py -- do not edit by hand.\n"
        "// Column-density tables for hydrogen-like orbitals in scaled units\n"
        "// (Z = 1). RGBA texel i holds (A_2p, B_2p, S_1s, S_2s) at\n"
        "// b = i * TABLE_B_MAX / (TABLE_N - 1).\n"
        f"export const TABLE_N = {n};\n"
        f"export const TABLE_B_MAX = {b_max!r};\n"
        f"export const TABLE_CHANNELS = {list(CHANNELS)!r};\n"
        "export const TABLE_DATA = new Float32Array([\n"
        + "\n".join(lines)
        + "\n]);\n"
    )
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write(src)


# ---------------------------------------------------------------- lookup
def lookup(rows, ch, b, b_max=B_MAX):
    """Linear interpolation, identical to the shader / js/math.js."""
    n = len(rows)
    x = b / b_max * (n - 1)
    if x >= n - 1:
        return 0.0
    i = int(x)
    f = x - i
    return rows[i][ch] * (1.0 - f) + rows[i + 1][ch] * f


# ---------------------------------------------------------------- Monte Carlo
def sample_1s(rng):
    # radial pdf r^2 exp(-2r): Gamma(3, 1/2)
    r = -0.5 * math.log(rng.random() * rng.random() * rng.random() or 1e-300)
    return _iso(rng, r)


def sample_2s(rng):
    # Radial pdf ~ r^2 (2-r)^2 exp(-r). Rejection sampling from the mixture
    # proposal q(r) = 0.5 Gamma(3,1) + 0.5 Gamma(5,1)
    #              ~ (r^2/4 + r^4/48) exp(-r).
    # p/q = (2-r)^2 / (1/4 + r^2/48) is bounded by 48 (its limit as r -> inf).
    while True:
        r = _gamma_int(rng, 3) if rng.random() < 0.5 else _gamma_int(rng, 5)
        q = 0.25 * r * r + r ** 4 / 48.0
        p = r * r * (2.0 - r) ** 2
        if rng.random() * 48.0 * q <= p:
            return _iso(rng, r)


def sample_2p(rng, axis):
    # radial pdf r^4 exp(-r): Gamma(5,1); angular pdf ~ cos^2(theta)
    r = _gamma_int(rng, 5)
    u = rng.random()
    c = u ** (1.0 / 3.0) * (1.0 if rng.random() < 0.5 else -1.0)
    s = math.sqrt(max(0.0, 1.0 - c * c))
    phi = 2.0 * math.pi * rng.random()
    v = [s * math.cos(phi) * r, s * math.sin(phi) * r, c * r]
    # v currently has its lobe along z; rotate so the lobe is along `axis`
    if axis == 0:
        v = [v[2], v[0], v[1]]
    elif axis == 1:
        v = [v[1], v[2], v[0]]
    return v


def _gamma_int(rng, k):
    p = 1.0
    for _ in range(k):
        p *= rng.random()
    return -math.log(p or 1e-300)


def _iso(rng, r):
    c = 2.0 * rng.random() - 1.0
    s = math.sqrt(1.0 - c * c)
    phi = 2.0 * math.pi * rng.random()
    return [r * s * math.cos(phi), r * s * math.sin(phi), r * c]


def mc_radial_histogram(samples, proj_axis, weight_axis=None, bin_w=0.5, nbins=16):
    """Histogram of impact parameter b when projecting along `proj_axis`.

    If weight_axis is given, also returns the per-bin sum of the squared
    coordinate along weight_axis (used to test the p_z^2 A(b) term).
    Returns per-bin fraction of samples (and optional weights).
    """
    counts = [0] * nbins
    for v in samples:
        q = [v[i] for i in range(3) if i != proj_axis]
        b = math.hypot(q[0], q[1])
        k = int(b / bin_w)
        if k < nbins:
            counts[k] += 1
    n = len(samples)
    return [c / n for c in counts]


def table_ring_mass(rows, kind, bin_w=0.5, nbins=16, sub=50):
    """Integral of the column density over annuli [k w, (k+1) w).

    kind: 's1', 's2'                  -> 2 pi b S(b)
          'p_along'  (ray || lobe)    -> 2 pi b B(b)
          'p_across' (ray _|_ lobe)   -> pi b^3 A(b)   (p_z^2 averaged = b^2/2)
    """
    out = []
    for k in range(nbins):
        acc = 0.0
        h = bin_w / sub
        for j in range(sub):
            b = (k * bin_w) + (j + 0.5) * h
            if kind == "s1":
                acc += 2 * math.pi * b * lookup(rows, 2, b)
            elif kind == "s2":
                acc += 2 * math.pi * b * lookup(rows, 3, b)
            elif kind == "p_along":
                acc += 2 * math.pi * b * lookup(rows, 1, b)
            elif kind == "p_across":
                acc += math.pi * b ** 3 * lookup(rows, 0, b)
        out.append(acc * h)
    return out


def monte_carlo_verify(rows, n_samples=200000, seed=1, verbose=True):
    """Compare MC histograms with the tables. Returns max abs error."""
    rng = random.Random(seed)
    cases = [
        ("1s", [sample_1s(rng) for _ in range(n_samples)], 2, "s1"),
        ("2s", [sample_2s(rng) for _ in range(n_samples)], 2, "s2"),
        ("2pz along z", [sample_2p(rng, 2) for _ in range(n_samples)], 2, "p_along"),
        ("2pz along x", [sample_2p(rng, 2) for _ in range(n_samples)], 0, "p_across"),
    ]
    worst = 0.0
    for name, samples, axis, kind in cases:
        mc = mc_radial_histogram(samples, axis)
        tb = table_ring_mass(rows, kind)
        err = max(abs(a - b) for a, b in zip(mc, tb))
        worst = max(worst, err)
        if verbose:
            print(f"  MC {name:12s} max |hist - table| = {err:.4f}"
                  f"  (table mass in bins: {sum(tb):.4f})")
    return worst


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--verify", action="store_true",
                    help="run Monte Carlo cross-check after generating")
    ap.add_argument("--out", default=OUT_PATH)
    args = ap.parse_args(argv)

    print(f"Building {len(CHANNELS)} tables x {N} samples, b in [0, {B_MAX}] ...")
    rows = build_tables()
    write_js(rows, args.out)
    print(f"Wrote {args.out}")

    # quick normalisation report
    h = B_MAX / (N - 1)
    norm = [0.0] * 4
    for i, row in enumerate(rows):
        b = i * h
        w = 0.5 if i in (0, N - 1) else 1.0
        norm[0] += w * math.pi * b ** 3 * row[0]
        norm[1] += w * 2 * math.pi * b * row[1]
        norm[2] += w * 2 * math.pi * b * row[2]
        norm[3] += w * 2 * math.pi * b * row[3]
    print("Normalisation (should all be 1):",
          ", ".join(f"{c}={v * h:.5f}" for c, v in zip(CHANNELS, norm)))

    if args.verify:
        print("Monte Carlo verification ...")
        worst = monte_carlo_verify(rows)
        ok = worst < 0.01
        print("PASS" if ok else "FAIL", f"(worst bin error {worst:.4f})")
        return 0 if ok else 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
